"""Write community/patches.json from the patch registry of this repository.

    python3 scripts/patches_snapshot.py                 write the file
    python3 scripts/patches_snapshot.py --check         exit 1 when the file differs from the registry
    uv run bafu-fixes list --json | python3 scripts/patches_snapshot.py --listing -

The registry is the patch tool's: every module in src/bafu_community_fixes/patches registers
its patch with `@patch(...)`, and `bafu-fixes list --json` prints what is registered. Nothing
about a patch is kept by hand anywhere else. The site and the checks of the records run
without the patch tool's environment (the tool needs Python 3.14 and its own packages), so
they read this file: for each patch its id, what it does, the findings it answers, its author
and who authorised it, and the address of its source. `python3 scripts/community.py check`
fails when the file differs from the registry, and names this script.

The file leaves out what the registry also holds and the site never shows: who reported the
problem, who confirmed it for the provider, and the references.

The registry is read in one of three ways, which give the same listing
(tests/test_registry.py compares them):

1. `--listing FILE` (or `-`): the JSON that `bafu-fixes list --json` printed;
2. the patch tool itself, when it can be imported from this repository's `src/` (that is,
   inside its environment: `uv run python scripts/patches_snapshot.py`);
3. otherwise the source of the patch modules, read without importing them. A patch whose
   `@patch(...)` is not written with plain values cannot be read this way; the script says so
   and the comparison is then left to a run inside the tool's environment.

Standard library only.
"""

import argparse
import ast
import contextlib
import io
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
PATCHES_FILE = "community/patches.json"
PATCH_FOLDER = "src/bafu_community_fixes/patches"
SCHEMA = "sentier-bafu/patches/2"
NOTE = (
    "The community patches of this repository, written by scripts/patches_snapshot.py from the "
    "patch registry (`bafu-fixes list --json`). Do not edit this file: change the patch, then run "
    "the script. `python3 scripts/community.py check` fails when the file differs from the "
    "registry. Patches are not copied into finding records: the site joins them to findings from "
    "this file."
)
MODULE = re.compile(r"p\d{4}_\w+\.py")
# How the registry was read; `community.py check` says it.
GIVEN, IMPORTED, SOURCE = "the listing given", "the patch tool, imported", "the source of the patch modules"


class Unreadable(Exception):
    """The registry is there and could not be read; the message says why."""


def has_registry(root=ROOT):
    return (Path(root) / PATCH_FOLDER).is_dir()


# ------------------------------------------------------------ the three ways to read it


def from_listing(text):
    """The patches in the JSON that `bafu-fixes list --json` prints."""
    try:
        steps = json.loads(text)
        return [dict(step) for step in steps if step["kind"] == "patch"]
    except (ValueError, TypeError, KeyError) as error:
        raise Unreadable(f"not the output of `bafu-fixes list --json` ({type(error).__name__})") from None


def from_package(root=ROOT):
    """The patches the patch tool lists, or None when the tool of this tree cannot be imported."""
    folder = (Path(root) / "src").resolve()
    try:
        import bafu_community_fixes
        from bafu_community_fixes import cli
    except Exception:  # not installed, another Python, a missing package: read the source instead
        return None
    if not Path(bafu_community_fixes.__file__).resolve().is_relative_to(folder):
        return None  # an installed patch tool of another checkout says nothing about this one
    printed = io.StringIO()
    with contextlib.redirect_stdout(printed):
        cli.main(["list", "--json"])
    return from_listing(printed.getvalue())


def constants(tree):
    """Module-level names bound to a string, such as ID = "0001-…"."""
    found = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Constant) and isinstance(node.value.value, str):
            for target in node.targets:
                if isinstance(target, ast.Name):
                    found[target.id] = node.value.value
    return found


def value(node, names):
    """A string, None, or a tuple of strings, as written in the decorator."""
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, ast.Name) and node.id in names:
        return names[node.id]
    if isinstance(node, (ast.Tuple, ast.List)):
        return tuple(value(item, names) for item in node.elts)
    raise ValueError(f"cannot read {ast.dump(node)[:80]}")


def registered(source, path):
    """The patches a module registers with @patch(...): [(registry id, arguments, description)]."""
    tree = ast.parse(source, filename=path)
    names = constants(tree)
    found = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef):
            continue
        for decorator in node.decorator_list:
            if not (isinstance(decorator, ast.Call) and getattr(decorator.func, "id", "") == "patch"):
                continue
            wanted = {"authored_by", "authorised_by", "references", "findings"}
            arguments = {k.arg: value(k.value, names) for k in decorator.keywords if k.arg in wanted}
            description = (ast.get_docstring(node) or "").strip().splitlines()
            if not description:
                raise ValueError(f"{path}: the patch has no docstring")
            found.append((value(decorator.args[0], names), arguments, description[0]))
    return found


def from_source(root=ROOT):
    """The patches the modules in the patch folder register, read without importing them."""
    listed = []
    for path in sorted((Path(root) / PATCH_FOLDER).glob("*.py")):
        if not MODULE.fullmatch(path.name):
            continue
        where = f"{PATCH_FOLDER}/{path.name}"
        try:
            found = registered(path.read_text(encoding="utf-8"), where)
            if len(found) != 1:
                raise ValueError(f"registers {len(found)} patches, not one")
            ((key, arguments, description),) = found
            listed.append({
                "id": key,
                "description": description,
                "findings": list(arguments["findings"]),
                "authored_by": arguments["authored_by"],
                "authorised_by": arguments.get("authorised_by"),
                "source": where,
            })
        except (ValueError, KeyError, SyntaxError) as error:
            raise Unreadable(
                f"{where} cannot be read without the patch tool ({type(error).__name__}: {error}); "
                "run `uv run python scripts/community.py check`, which reads the registry itself"
            ) from None
    return listed


def listing(root=ROOT, given=None):
    """(the patches of the registry in `root`, how they were read)."""
    if given is not None:
        return from_listing(given), GIVEN
    found = from_package(root)
    if found is not None:
        return found, IMPORTED
    return from_source(root), SOURCE


# --------------------------------------------------------------------------- the file


def snapshot(listed, repository, ref="main"):
    """What community/patches.json holds for the patches of a listing."""
    patches = []
    for step in listed:
        number, _, slug = step["id"].partition("-")
        patches.append({
            "id": number,
            "slug": slug,
            "description": step["description"],
            "findings": sorted(set(step["findings"]), key=lambda rid: int(rid[1:])),
            "author": step["authored_by"],
            "authorised_by": step.get("authorised_by"),
            "url": f"{repository}/blob/{ref}/{step['source']}",
        })
    return {
        "schema": SCHEMA,
        "note": NOTE,
        "source": {"repository": repository, "ref": ref, "path": PATCH_FOLDER},
        "patches": sorted(patches, key=lambda patch: patch["id"]),
    }


def expected(root=ROOT, given=None):
    """(what the file must hold, how the registry was read); (None, None) in a tree without a registry.

    Raises Unreadable when the registry is there and cannot be read.
    """
    root = Path(root)
    if given is None and not has_registry(root):
        return None, None
    config = json.loads((root / "site/config.json").read_text(encoding="utf-8"))
    listed, how = listing(root, given)
    return snapshot(listed, config["repository"], config.get("source_ref", "main")), how


def differences(committed, wanted):
    """In words, how the committed file differs from what the registry gives; [] when it does not."""
    if committed == wanted:
        return []
    if not isinstance(committed, dict) or not isinstance(committed.get("patches"), list):
        return ["it is not a list of patches"]
    have = {p.get("id"): p for p in committed["patches"] if isinstance(p, dict)}
    want = {p["id"]: p for p in wanted["patches"]}
    found = [f"patch {pid} is in the registry and not in the file" for pid in sorted(set(want) - set(have))]
    found += [f"patch {pid} is in the file and not in the registry" for pid in sorted(set(have) - set(want), key=str)]
    for pid in sorted(set(want) & set(have)):
        keys = sorted(key for key in set(want[pid]) | set(have[pid]) if want[pid].get(key) != have[pid].get(key))
        if keys:
            found.append(f"patch {pid} differs in {', '.join(keys)}")
    return found or ["its header (schema, note or source) is not the one the script writes"]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    parser.add_argument("--out", type=Path, help=f"where to write (default: {PATCHES_FILE} of the repository)")
    parser.add_argument("--listing", metavar="FILE", help="the output of `bafu-fixes list --json`; `-` reads it from the input")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 when the file differs from the registry")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    out = args.out or root / PATCHES_FILE
    given = None
    if args.listing:
        given = sys.stdin.read() if args.listing == "-" else Path(args.listing).read_text(encoding="utf-8")
    try:
        data, how = expected(root, given)
    except Unreadable as problem:
        print(problem)
        return 1
    if data is None:
        print(f"{PATCH_FOLDER} is not in this tree: there is no registry to read")
        return 1
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import community  # here, not at the top: community.py reads this module when it checks

    problems = community.patch_errors(data)
    if problems:
        print("\n".join(problems))
        return 1
    with_finding = sum(bool(patch["findings"]) for patch in data["patches"])
    counted = f"{len(data['patches'])} patches, {with_finding} answer a finding (read from {how})"
    if args.check:
        found = differences(json.loads(out.read_text(encoding="utf-8")) if out.exists() else None, data)
        if found:
            print(f"{out}: differs from the registry: " + "; ".join(found[:10]))
            print("Run `python3 scripts/patches_snapshot.py`.")
            return 1
        print(f"{out}: {counted}; the file is what the registry gives")
        return 0
    out.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{out}: {counted}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
